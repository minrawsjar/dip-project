"""Rewrite the headline-results block of README.md from results/*.csv.

Run after `ekyc eval ...` / `ekyc ablate ...` so the README always matches the CSVs.
Usage: python scripts/summarize_results.py
"""

import re

import pandas as pd

from ekyc.io import ROOT, git_hash

R = ROOT / "results"
pct = lambda v: "—" if pd.isna(v) else f"{100 * v:.1f}%"
num = lambda v, d=2: "—" if pd.isna(v) else f"{v:.{d}f}"


def read(name):
    p = R / f"{name}.csv"
    return pd.read_csv(p) if p.exists() else None


out = [
    "## Headline results",
    "",
    f"_Generated by `scripts/summarize_results.py` from `results/*.csv` (commit `{git_hash()}`)._",
    "",
]

if (f := read("face_summary")) is not None:
    out += [
        "**Face verification** (EER with 95% bootstrap CI; lower is better)",
        "",
        "| Dataset | Baseline: Haar + landmark distances | Improved: YuNet + align + HSV-V + SFace | TAR@FAR=1e-2 (improved) |",
        "|---|---|---|---|",
    ]
    for ds, g in f.groupby("dataset", sort=False):
        b, i = g[g.variant == "baseline"].iloc[0], g[g.variant == "improved"].iloc[0]
        out.append(
            f"| {ds} | {pct(b.EER)} [{pct(b.EER_lo)}, {pct(b.EER_hi)}] | **{pct(i.EER)}** [{pct(i.EER_lo)}, {pct(i.EER_hi)}] "
            f"| {pct(i['TAR@FAR=1e-2'])} |"
        )
    out.append("")

if (d := read("document_summary")) is not None:
    d = d.rename(columns={"iou>0.9": "iou_gt_09"})
    out += [
        "**Document** (synthetic captured cards"
        + (" + MIDV-2020" if "midv2020" in set(d.source) else "")
        + ")",
        "",
        "| Source | Variant | Quad IoU | IoU > 0.9 | Corner error (px) | Field CER | Exact fields |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in d.itertuples():
        out.append(
            f"| {r.source} | {r.variant} | {num(r.iou, 3)} | {pct(r.iou_gt_09)} | {num(r.corner_err, 1)} "
            f"| {pct(r.cer)} | {pct(r.exact)} |"
        )
    out.append("")

if (e := read("E12")) is not None:
    out += [
        "**E12: where the face gain comes from** (EER)",
        "",
        "| Variant | LFW | Synthetic doc-vs-selfie |",
        "|---|---|---|",
    ]
    piv = e.pivot_table(index="variant", columns="dataset", values="EER", sort=False)
    for v, r in piv.iterrows():
        out.append(f"| {v} | {pct(r.get('lfw'))} | {pct(r.get('synthetic_doc'))} |")
    out.append("")

lines = []
if (x := read("E1")) is not None:
    lines.append(
        "- **E1 bit depth:** EER "
        + ", ".join(f"{int(r.bits)} bit {pct(r.EER)}" for r in x.itertuples())
        + "."
    )
if (x := read("E2")) is not None:
    s = x[x.scale == x.scale.min()]
    lines.append(
        f"- **E2 interpolation at 1/{round(1 / s.scale.iloc[0])} resolution:** "
        + ", ".join(f"{r.interp} {pct(r.EER)}" for r in s.itertuples())
        + "."
    )
if (x := read("E3")) is not None:
    lines.append(
        "- **E3 JPEG:** EER "
        + ", ".join(f"q{int(r.quality)} {pct(r.EER)}" for r in x.itertuples())
        + "; OCR CER "
        + ", ".join(f"q{int(r.quality)} {pct(r.CER)}" for r in x.itertuples())
        + "."
    )
if (x := read("E4")) is not None:
    lines.append(
        "- **E4 low-light enhancement:** OCR CER "
        + ", ".join(f"{r.method} {pct(r.CER)}" for r in x.itertuples())
        + "; face EER "
        + ", ".join(f"{r.method} {pct(r.EER)}" for r in x.itertuples())
        + "."
    )
if (x := read("E5")) is not None:
    lines.append(
        "- **E5 colour:** hue shift "
        + ", ".join(f"{r.mode} {r.hue_shift_deg:.1f}°" for r in x.itertuples())
        + "; EER "
        + ", ".join(f"{r.mode} {pct(r.EER)}" for r in x.itertuples())
        + "."
    )
if (x := read("E6")) is not None:
    lines.append(
        "- **E6 edge operator:** quad IoU "
        + ", ".join(f"{r.edge} {num(r.iou, 3)}" for r in x.itertuples())
        + "."
    )
if (x := read("E7")) is not None:
    lines.append(
        "- **E7 corners:** mean corner error "
        + ", ".join(f"{r.corner} {num(r.corner_err, 1)} px" for r in x.itertuples())
        + "."
    )
if (x := read("E8")) is not None:
    lines.append(
        "- **E8 denoising (CER):** "
        + "; ".join(
            f"{n}: " + ", ".join(f"{r.filter} {pct(r.CER)}" for r in g.itertuples())
            for n, g in x.groupby("noise", sort=False)
        )
        + "."
    )
if (x := read("E9")) is not None:
    lines.append(
        "- **E9 thresholding (CER):** "
        + "; ".join(
            f"{c}: " + ", ".join(f"{r.threshold} {pct(r.CER)}" for r in g.itertuples())
            for c, g in x.groupby("condition", sort=False)
        )
        + "."
    )
if (x := read("E13")) is not None:
    lines.append(
        "- **E13 quality gate:** "
        + "; ".join(
            f"gate {r.quality_gate}: FRR {pct(r.FRR)}, CER {pct(r.CER)}, retake {pct(r.retake_rate)}"
            for r in x.itertuples()
        )
        + "."
    )
if (x := read("E14")) is not None:
    lines.append(
        "- **E14 fusion:** "
        + "; ".join(f"{r.method}: FAR {pct(r.FAR)}, FRR {pct(r.FRR)}" for r in x.itertuples())
        + f". _{x.note.iloc[0]}_"
    )
for e in ("E10", "E11"):
    if read(e) is None:
        lines.append(f"- **{e}:** pending own-capture liveness clips (`data/own_capture/`).")
if lines:
    out += ["**Ablations**", "", *lines, ""]

readme = ROOT / "README.md"
text = readme.read_text()
block = "<!-- RESULTS:START -->\n" + "\n".join(out) + "\n<!-- RESULTS:END -->"
readme.write_text(
    re.sub(r"<!-- RESULTS:START -->.*?<!-- RESULTS:END -->", lambda _: block, text, flags=re.DOTALL)
)
print("\n".join(out))
